package imaging

import (
	"errors"
	"image"
	"math"
)

// Mipmap generation errors.
var (
	// ErrMipmapEmptyImage means the source image is nil or has empty bounds.
	ErrMipmapEmptyImage = errors.New("imaging: mipmap: source image is empty")

	// ErrMipmapInvalidMaxLevels means MaxLevels is negative.
	ErrMipmapInvalidMaxLevels = errors.New("imaging: mipmap: MaxLevels must not be negative")

	// ErrMipmapInvalidMaxPixels means MaxPixels is negative.
	ErrMipmapInvalidMaxPixels = errors.New("imaging: mipmap: MaxPixels must not be negative")

	// ErrMipmapTooLarge means the total number of pixels in the generated
	// levels exceeds the pixel budget (MaxPixels or DefaultMipmapMaxPixels).
	ErrMipmapTooLarge = errors.New("imaging: mipmap: image exceeds the pixel limit")

	// ErrMipmapSizeOverflow means the image dimensions or the byte size of
	// one of the levels cannot be represented by the platform integer type.
	ErrMipmapSizeOverflow = errors.New("imaging: mipmap: image dimensions overflow")
)

// DefaultMipmapMaxPixels is the default limit for the total number of pixels
// stored in all generated mipmap levels, including the base level. At four
// bytes per pixel this is about 512 MiB of image data; a full chain is less
// than twice the base level unless one dimension is tiny. This fits an 8K
// square base texture with room for the smaller levels. Larger textures can
// be generated by raising MaxPixels explicitly.
const DefaultMipmapMaxPixels int64 = 1 << 27

// MipmapOptions controls mipmap generation. The zero value is valid and
// produces a complete mipmap chain in sRGB color space with the default
// memory limit.
type MipmapOptions struct {
	// LinearLight resamples in linear RGB instead of the (sRGB-encoded)
	// values stored in the image. This produces physically correct
	// averages, e.g. a black and a white pixel average to a medium gray
	// that is brighter than 8-bit 128, avoiding the darkening of
	// high-contrast details. Alpha is always processed linearly.
	LinearLight bool

	// MaxLevels is the maximum number of levels to return, including the
	// base level. Zero (the default) builds the complete chain down to
	// 1x1. Values larger than the complete chain are clamped to it.
	// Negative values return ErrMipmapInvalidMaxLevels.
	MaxLevels int

	// MaxPixels is the maximum total number of pixels across all returned
	// levels, including the base level. Zero selects
	// DefaultMipmapMaxPixels. Negative values return
	// ErrMipmapInvalidMaxPixels, and an image that exceeds the limit
	// returns ErrMipmapTooLarge.
	MaxPixels int64
}

// GenerateMipmaps builds a mipmap chain from img and returns the levels in
// decreasing size order: index 0 is the base level, followed by each
// successively smaller level down to 1x1 (unless MaxLevels truncates the
// chain).
//
// Every level is a zero-origin *image.NRGBA ready to be uploaded as one
// texture mip level. The dimensions of a level are max(1, width/2) by
// max(1, height/2) of the previous level, matching the mip level dimensions
// used by graphics APIs. Odd source sizes are therefore handled correctly:
// the final row/column is not dropped, but contributes to the last
// destination pixel with its correct area coverage, and the chain still
// reaches 1x1.
//
// Downsampling is done with an area-weighted box filter operating on
// premultiplied alpha. Color from fully transparent pixels therefore cannot
// bleed into visible pixels, which prevents the dark fringes that appear
// around transparent edges (e.g. cut-out foliage) when a texture is displayed
// minified. If LinearLight is set, the sRGB values are converted to linear
// RGB before filtering and encoded back to sRGB afterwards; alpha is averaged
// linearly in both modes. Level 0 is an exact copy of the input and Resize is
// not affected by these settings.
//
// The input image is only read, never modified. The returned slice and all
// levels are newly allocated.
//
// GenerateMipmaps returns:
//   - ErrMipmapEmptyImage if img is nil or has empty bounds;
//   - ErrMipmapInvalidMaxLevels if MaxLevels is negative;
//   - ErrMipmapInvalidMaxPixels if MaxPixels is negative;
//   - ErrMipmapSizeOverflow if the dimensions or the allocation size of a
//     level overflow the platform integer type;
//   - ErrMipmapTooLarge if the total number of pixels of all levels exceeds
//     MaxPixels (or DefaultMipmapMaxPixels when MaxPixels is zero).
//
// On any error no levels are returned. The dimensions and memory budget are
// checked before any level is allocated, so a rejected image never causes a
// partial or oversized allocation.
//
// Example:
//
//	// Build an uploadable mipmap chain for a transparent foliage texture.
//	levels, err := imaging.GenerateMipmaps(leafTexture, imaging.MipmapOptions{
//		LinearLight: true,
//	})
//	if err != nil {
//		// handle an empty, oversized or overflowing image
//	}
//	for i, mip := range levels {
//		// upload mip.Pix as texture mip level i (mip.Rect.Dx() x mip.Rect.Dy())
//		_ = i
//	}
func GenerateMipmaps(img image.Image, opts MipmapOptions) ([]*image.NRGBA, error) {
	if opts.MaxLevels < 0 {
		return nil, ErrMipmapInvalidMaxLevels
	}
	if opts.MaxPixels < 0 {
		return nil, ErrMipmapInvalidMaxPixels
	}
	if img == nil {
		return nil, ErrMipmapEmptyImage
	}

	bounds := img.Bounds()
	if bounds.Max.X <= bounds.Min.X || bounds.Max.Y <= bounds.Min.Y {
		return nil, ErrMipmapEmptyImage
	}

	// Compute the differences with unsigned arithmetic so that extreme
	// rectangle coordinates cannot overflow before the sanity checks.
	width := uint64(bounds.Max.X) - uint64(bounds.Min.X)
	height := uint64(bounds.Max.Y) - uint64(bounds.Min.Y)

	// maxInt is the largest value representable by int, and maxInt64 the
	// largest int64 value. Deriving them from the types (instead of using
	// math.MaxInt64) keeps this portable to 32-bit platforms and buildable
	// with older Go versions.
	maxInt := int64(^uint(0) >> 1)
	const maxInt64 = int64(^uint64(0) >> 1)
	if width > uint64(maxInt) || height > uint64(maxInt) {
		return nil, ErrMipmapSizeOverflow
	}

	maxPixels := opts.MaxPixels
	if maxPixels == 0 {
		maxPixels = DefaultMipmapMaxPixels
	}

	// Plan the whole chain and validate its size before allocating any
	// pixel buffers.
	type levelSize struct{ w, h int64 }
	sizes := make([]levelSize, 0, 32)
	var total int64
	w, h := int64(width), int64(height)
	for {
		if h != 0 && w > maxInt64/h {
			return nil, ErrMipmapSizeOverflow
		}
		area := w * h
		// image.NRGBA stores four bytes per pixel, so the byte size of a
		// level must fit into int. Together with the overflow check above
		// this also bounds the running total, which is less than twice the
		// base level area.
		if area > maxInt/4 {
			return nil, ErrMipmapSizeOverflow
		}
		total += area
		if total > maxPixels {
			return nil, ErrMipmapTooLarge
		}
		sizes = append(sizes, levelSize{w: w, h: h})

		if (opts.MaxLevels > 0 && len(sizes) >= opts.MaxLevels) || (w == 1 && h == 1) {
			break
		}
		w /= 2
		h /= 2
		if w < 1 {
			w = 1
		}
		if h < 1 {
			h = 1
		}
	}

	levels := make([]*image.NRGBA, len(sizes))
	levels[0] = Clone(img)
	for i := 1; i < len(sizes); i++ {
		levels[i] = mipmapDownsample(levels[i-1], int(sizes[i].w), int(sizes[i].h), opts.LinearLight)
	}
	return levels, nil
}

// mipmapAxisWeight is one source index and its normalized coverage weight
// along one axis for a single destination index.
type mipmapAxisWeight struct {
	index  int
	weight float64
}

// mipmapAxisWeights computes area coverage weights for downsampling an axis
// of src pixels to dst pixels. Each destination pixel covers the source
// interval [d*scale, (d+1)*scale); a source pixel contributes its overlap
// with that interval. The weights of every destination pixel sum to 1.
//
// dst must be <= src and both must be positive.
func mipmapAxisWeights(dst, src int) [][]mipmapAxisWeight {
	scale := float64(src) / float64(dst)
	weights := make([][]mipmapAxisWeight, dst)
	for d := 0; d < dst; d++ {
		start := float64(d) * scale
		end := float64(d+1) * scale

		first := int(math.Floor(start))
		last := int(math.Ceil(end))
		// Floating-point rounding can push the computed upper boundary one
		// pixel past the source, so clamp it defensively.
		if last > src {
			last = src
		}

		var sum float64
		ws := make([]mipmapAxisWeight, 0, 4)
		for i := first; i < last; i++ {
			overlap := math.Min(end, float64(i+1)) - math.Max(start, float64(i))
			ws = append(ws, mipmapAxisWeight{index: i, weight: overlap})
			sum += overlap
		}
		if sum > 0 {
			inv := 1 / sum
			for i := range ws {
				ws[i].weight *= inv
			}
		}
		weights[d] = ws
	}
	return weights
}

// mipmapDownsample scales src to dstW x dstH using an area-weighted box
// filter with premultiplied alpha. When linear is true the color channels are
// converted from sRGB to linear RGB before filtering and back afterwards.
func mipmapDownsample(src *image.NRGBA, dstW, dstH int, linear bool) *image.NRGBA {
	dst := image.NewNRGBA(image.Rect(0, 0, dstW, dstH))
	xWeights := mipmapAxisWeights(dstW, src.Rect.Dx())
	yWeights := mipmapAxisWeights(dstH, src.Rect.Dy())

	parallel(0, dstH, func(ys <-chan int) {
		for y := range ys {
			yws := yWeights[y]
			dstOff := y * dst.Stride
			for x := 0; x < dstW; x++ {
				var r, g, b, a float64
				for _, yw := range yws {
					rowOff := yw.index * src.Stride
					for _, xw := range xWeights[x] {
						off := rowOff + xw.index*4
						// Premultiply: the contribution of a pixel is
						// proportional to its alpha, so transparent pixels
						// never influence the resulting color.
						aw := float64(src.Pix[off+3]) * (1.0 / 255.0) * xw.weight * yw.weight
						if aw == 0 {
							continue
						}
						if linear {
							r += mipmapSRGBToLinear[src.Pix[off+0]] * aw
							g += mipmapSRGBToLinear[src.Pix[off+1]] * aw
							b += mipmapSRGBToLinear[src.Pix[off+2]] * aw
						} else {
							r += float64(src.Pix[off+0]) * (1.0 / 255.0) * aw
							g += float64(src.Pix[off+1]) * (1.0 / 255.0) * aw
							b += float64(src.Pix[off+2]) * (1.0 / 255.0) * aw
						}
						a += aw
					}
				}

				px := dst.Pix[dstOff : dstOff+4 : dstOff+4]
				if a > 0 {
					inv := 1 / a
					if linear {
						px[0] = clamp(mipmapLinearToSRGB(r*inv) * 255)
						px[1] = clamp(mipmapLinearToSRGB(g*inv) * 255)
						px[2] = clamp(mipmapLinearToSRGB(b*inv) * 255)
					} else {
						px[0] = clamp(r * inv * 255)
						px[1] = clamp(g * inv * 255)
						px[2] = clamp(b * inv * 255)
					}
					px[3] = clamp(a * 255)
				}
				// If a == 0 the pixel is fully transparent. Its color stays
				// zero instead of averaging the (meaningless) RGB values of
				// fully transparent source pixels.

				dstOff += 4
			}
		}
	})
	return dst
}

// mipmapSRGBToLinear maps 8-bit sRGB values to linear RGB in [0, 1].
var mipmapSRGBToLinear [256]float64

// mipmapLinearToSRGB maps a linear RGB value in [0, 1] to sRGB in [0, 1].
func mipmapLinearToSRGB(v float64) float64 {
	if v <= 0 {
		return 0
	}
	if v >= 1 {
		return 1
	}
	if v <= 0.0031308 {
		return v * 12.92
	}
	return 1.055*math.Pow(v, 1.0/2.4) - 0.055
}

func init() {
	for i := range mipmapSRGBToLinear {
		v := float64(i) / 255
		if v <= 0.04045 {
			mipmapSRGBToLinear[i] = v / 12.92
		} else {
			mipmapSRGBToLinear[i] = math.Pow((v+0.055)/1.055, 2.4)
		}
	}
}
